"""Run the hardware suites against a named card, record what the simulated cards cover, and
render both as the book's test results and the release notes' tables.

    hardware-tests --card yubikey-5.7 --suite touch-free [--applet piv|pgp]
    hardware-tests --card yubikey-5.7 --suite attended
    hardware-tests --simulated
    hardware-tests --render [--check]

Expectations live in harness/expected.toml, results in harness/results/, one file per card,
suite and applet and one for the simulated cards. A run writes its results whatever they
are; committing them is what makes a run the official one. The serials of the cards a run
may reset are in the local, git-ignored .env, as `<card>=<serial>`, never in a result.
"""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

EXPECTED = Path("harness/expected.toml")
RESULTS = Path("harness/results")
CHAPTER = Path("docs/test-results.md")
RELEASES = Path("docs/releases.md")
ENV = Path(".env")

APPLETS = {"piv": "PIV", "pgp": "OpenPGP"}
SUITES = ("touch-free", "attended")
ALGORITHMS = [
    ("p256", "P-256"),
    ("p384", "P-384"),
    ("curve25519", "Curve25519"),
    ("rsa2048", "RSA-2048"),
    ("rsa3072", "RSA-3072"),
    ("rsa4096", "RSA-4096"),
    ("touch", "Touch refused"),
]
GENERATED = (
    "<!-- Generated by `nix run .#hardware-tests -- --render` from harness/expected.toml and\n"
    "harness/results/; change those, then render again, rather than this page. -->"
)


def fail(message):
    sys.exit(f"hardware-tests: {message}")


def run(command, **kwargs):
    return subprocess.run(command, check=False, text=True, capture_output=True, **kwargs)


def expected():
    if not EXPECTED.exists():
        fail(f"{EXPECTED} not found; run this from the repository root")
    return tomllib.loads(EXPECTED.read_text())


def version():
    """The release the tree is, as Cargo.toml names it"""
    found = re.search(r'^version = "([^"]+)"', Path("Cargo.toml").read_text(), re.M)
    return found.group(1) if found else "unknown"


def provenance():
    """The tool's version and the commit the run was made from, marked when uncommitted"""
    commit = run(["git", "rev-parse", "--short", "HEAD"]).stdout.strip() or "unknown"
    if run(["git", "status", "--porcelain", "--untracked-files=no"]).stdout.strip():
        commit += "+changes"
    return version(), commit


def today():
    return datetime.date.today().isoformat()


# ---------------------------------------------------------------- results files

def quote(text):
    return json.dumps(text, ensure_ascii=False)


def write_results(path, header, sections):
    """A results file: run facts as top-level keys, then a table per section"""
    lines = [
        "# Written by `nix run .#hardware-tests`; committing it makes it the official run.",
        "",
    ]
    lines += [f"{key} = {quote(value)}" for key, value in header.items()]
    for name, rows in sections.items():
        lines += ["", f"[{name}]"]
        for key, fields in rows.items():
            inner = ", ".join(f"{field} = {quote(value)}" for field, value in fields.items())
            lines.append(f"{quote(key)} = {{ {inner} }}")
    RESULTS.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {path}")


def read_results():
    found = {}
    if RESULTS.is_dir():
        for path in sorted(RESULTS.glob("*.toml")):
            found[path.stem] = tomllib.loads(path.read_text())
    return found


# ---------------------------------------------------------------- the card

def serial_of(card):
    """The serial the local .env gives the card, which never leaves this machine"""
    if not ENV.exists():
        fail(f"no {ENV}: name the spare cards there as `<card>=<serial>` (docs/hardware-tests.md)")
    for line in ENV.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if "=" in line:
            name, value = (part.strip() for part in line.split("=", 1))
            if name == card:
                return value
    fail(f"{ENV} names no card `{card}`")


def find_card(serial):
    """The reader holding the card with this PIV serial, its firmware and OpenPGP identifier

    Asks each card only to select its applets and answer with its serial and versions,
    in shared mode, so no card is reset and none is held.
    """
    from smartcard.System import readers

    piv_aid = [0xA0, 0x00, 0x00, 0x03, 0x08]
    pgp_aid = [0xD2, 0x76, 0x00, 0x01, 0x24, 0x01]
    otp_aid = [0xA0, 0x00, 0x00, 0x05, 0x27, 0x20, 0x01, 0x01]
    select = lambda aid: [0x00, 0xA4, 0x04, 0x00, len(aid)] + aid + [0x00]
    seen, busy = [], []
    for reader in readers():
        seen.append(str(reader))
        connection = reader.createConnection()
        try:
            connection.connect()
        except Exception:
            # Held by another program, such as gpg's scdaemon, which takes cards exclusively
            busy.append(str(reader))
            continue
        try:
            _, sw1, _ = connection.transmit(select(piv_aid))
            if sw1 not in (0x90, 0x61):
                continue
            version, sw1, _ = connection.transmit([0x00, 0xFD, 0x00, 0x00, 0x00])
            firmware = ".".join(str(part) for part in version) if sw1 == 0x90 else ""
            # GET SERIAL came with firmware 5; a YubiKey 4 tells its serial through the OTP
            # application, as yubikey.rs reads it
            data, sw1, sw2 = connection.transmit([0x00, 0xF8, 0x00, 0x00, 0x00])
            if (sw1, sw2) != (0x90, 0x00) and firmware.startswith("4."):
                connection.transmit(select(otp_aid))
                data, sw1, sw2 = connection.transmit([0x00, 0x01, 0x10, 0x00, 0x00])
            if (sw1, sw2) != (0x90, 0x00) or int.from_bytes(bytes(data), "big") != int(serial):
                continue
            ident, openpgp = None, ""
            _, sw1, _ = connection.transmit(select(pgp_aid))
            if sw1 in (0x90, 0x61):
                aid, sw1, _ = connection.transmit([0x00, 0xCA, 0x00, 0x4F, 0x00])
                if sw1 == 0x90 and len(aid) >= 14:
                    openpgp = f"{aid[6]}.{aid[7]}"
                    ident = "{:04X}:{:08X}".format(
                        int.from_bytes(bytes(aid[8:10]), "big"),
                        int.from_bytes(bytes(aid[10:14]), "big"),
                    )
            # The reader's own index ("00 00") says nothing about the card
            name = re.sub(r"( \d\d)+$", "", str(reader))
            return name, firmware, openpgp, ident
        finally:
            connection.disconnect()
    held = f"; held by another program: {', '.join(busy)}" if busy else ""
    fail(f"no attached card has the PIV serial {serial} (readers: {', '.join(seen) or 'none'}{held})")


# ---------------------------------------------------------------- a suite run

def outcomes(output):
    """Each test's outcome from a libtest run: passed, failed, or refused (failed saying
    the card was not touched)"""
    ran = re.findall(r"^test (\S+) \.\.\. ", output, re.M)
    failed = set()
    tail = output.rsplit("\nfailures:\n", 1)
    if len(tail) == 2:
        failed = set(re.findall(r"^    (\S+)$", tail[1], re.M))
    starts = [(match.start(), match.group(1)) for match in re.finditer(r"^test (\S+) \.\.\. ", output, re.M)]
    found = {}
    for index, (start, name) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(output)
        if name not in failed:
            found[name] = "pass"
        elif "was not touched" in output[start:end]:
            found[name] = "refused"
        else:
            found[name] = "fail"
    for name in ran:
        found.setdefault(name, "fail" if name in failed else "pass")
    return found


def run_card(card, suite, only):
    profiles = expected()["cards"]
    if card not in profiles:
        fail(f"harness/expected.toml has no card `{card}`; known: {', '.join(profiles)}")
    profile = profiles[card]
    serial = serial_of(card)
    reader, firmware, openpgp, ident = find_card(serial)
    if not firmware.startswith(profile.get("firmware", "")) and profile.get("firmware"):
        fail(f"the card reports firmware {firmware}, where `{card}` expects {profile['firmware']}*")
    print(f"{card}: {reader}, PIV firmware {firmware or 'unreported'}, OpenPGP {openpgp or 'none'}")

    # gpg's scdaemon holds a card exclusively once it has seen it, and would stall the suite
    run(["gpgconf", "--kill", "scdaemon"])

    tool, commit = provenance()
    mismatches = 0
    for applet in [only] if only else APPLETS:
        tests = profile.get(applet, {})
        to_run = [name for name, want in tests.items() if not want.startswith("skip")]
        if not to_run:
            continue
        env = dict(os.environ)
        env.update({key: str(value) for key, value in profile.get("env", {}).items()})
        env["MTG_HARDWARE_TEST_SERIAL"] = serial
        if ident:
            env["MTG_HARDWARE_TEST_CARD"] = ident
        if suite == "touch-free":
            env["MTG_HARDWARE_TEST_TOUCH"] = "never"
        else:
            env.pop("MTG_HARDWARE_TEST_TOUCH", None)
        binary = os.environ[f"MTG_{applet.upper()}_SUITE"]
        command = [binary, "--include-ignored", "--exact", *to_run, "--test-threads", "1", "--nocapture"]
        print(f"\n== {APPLETS[applet]}, {suite}: {len(to_run)} tests" + (" -- TOUCH the card when it blinks" if suite == "attended" else ""))
        # Shown as it runs, for the touches, and kept for the outcomes
        process = subprocess.Popen(command, env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        output = []
        for line in process.stdout:
            sys.stdout.write(line)
            output.append(line)
        process.wait()
        got = outcomes("".join(output))

        rows = {}
        for name, want in tests.items():
            outcome = "skipped" if want.startswith("skip") else got.get(name, "not run")
            rows[name] = {"expected": want, "outcome": outcome}
            if not want.startswith("skip") and outcome != want:
                mismatches += 1
                print(f"MISMATCH {applet} {name}: expected {want}, got {outcome}")
        header = {
            "card": card,
            "name": profile["name"],
            "reader": reader,
            "firmware": firmware,
            "openpgp": openpgp,
            "applet": APPLETS[applet],
            "suite": suite,
            "date": today(),
            "tool": tool,
            "commit": commit,
        }
        write_results(RESULTS / f"{card}.{suite}.{applet}.toml", header, {"tests": rows})
    if mismatches:
        fail(f"{mismatches} outcomes differ from harness/expected.toml")
    print("\nEvery outcome as expected")


# ---------------------------------------------------------------- simulated cards

def sources():
    """Every source a simulated card is built from: the flake inputs as locked, and the
    nixpkgs packages at the locked nixpkgs"""
    nodes = json.loads(Path("flake.lock").read_text())["nodes"]

    def locked(name):
        node = nodes.get(name, {})
        lock, original = node.get("locked", {}), node.get("original", {})
        where = f"{lock.get('owner')}/{lock.get('repo')}" if lock.get("owner") else lock.get("url", "")
        ref = original.get("ref", "").removeprefix("refs/tags/")
        return f"{where} {ref + ' ' if ref else ''}@ {lock.get('rev', '')[:12]}".strip()

    def package(name):
        result = run(["nix", "eval", "--raw", "--inputs-from", ".", f"nixpkgs#{name}.version"])
        return f"{name} {result.stdout.strip() or 'unknown'} (nixpkgs @ {nodes['nixpkgs']['locked']['rev'][:12]})"

    return lambda source: package(source.removeprefix("nixpkgs:")) if source.startswith("nixpkgs:") else locked(source)


def run_simulated():
    system = run(["nix", "eval", "--raw", "--impure", "--expr", "builtins.currentSystem"]).stdout.strip()
    source_of = sources()
    tool, commit = provenance()
    rows = {}
    failed = 0
    for name, card in expected()["simulated"].items():
        results = {}
        for check in card["checks"]:
            print(f"== {check}")
            build = subprocess.run(["nix", "build", "--no-link", "-L", f".#checks.{system}.{check}"], check=False)
            results[check] = "pass" if build.returncode == 0 else "fail"
        outcome = "pass" if all(value == "pass" for value in results.values()) else "fail"
        failed += outcome != "pass"
        rows[name] = {
            "outcome": outcome,
            "checks": ", ".join(f"{check} {value}" for check, value in results.items()),
            "sources": "; ".join(source_of(source) for source in card["sources"]),
        }
    header = {"system": system, "date": today(), "tool": tool, "commit": commit}
    write_results(RESULTS / "simulated.toml", header, {"cards": rows})
    if failed:
        fail(f"{failed} simulated cards failed their checks")


# ---------------------------------------------------------------- rendering

def mark(value):
    symbols = {"pass": "✓", "refused": "refused", "open": "○", "-": "—"}
    head, _, note = value.partition(" (")
    return symbols.get(head, head) + (f" ({note}" if note else "")


def card_tables(want, found):
    """The real cards: a summary row per card and suite, then each card's tests"""
    lines = [
        "| Card | Firmware | Suite | Run | PIV | OpenPGP |",
        "|---|---|---|---|---|---|",
    ]
    details = []
    for card, profile in want["cards"].items():
        for suite in SUITES:
            runs = {applet: found.get(f"{card}.{suite}.{applet}") for applet in APPLETS}
            if not any(runs.values()):
                lines.append(f"| {profile['name']} | | {suite} | not run yet | | |")
                continue
            first = next(result for result in runs.values() if result)
            cells = []
            for applet, result in runs.items():
                if not result:
                    cells.append("not run yet")
                    continue
                tests = result["tests"]
                counted = [row for row in tests.values() if not row["expected"].startswith("skip")]
                agree = sum(row["outcome"] == row["expected"] for row in counted)
                cells.append(f"{agree} of {len(counted)} as expected" if agree < len(counted) else f"all {len(counted)} as expected")
            firmware = first["firmware"] or "unreported"
            lines.append(
                f"| {profile['name']} | {firmware} | {suite} | {first['date']}, {first['commit']} | {cells[0]} | {cells[1]} |"
            )
        rows = []
        for applet, label in APPLETS.items():
            for test, expectation in profile.get(applet, {}).items():
                outcome = []
                for suite in SUITES:
                    result = found.get(f"{card}.{suite}.{applet}")
                    row = result["tests"].get(test) if result else None
                    outcome.append(row["outcome"] if row else "")
                rows.append(f"| {label} | `{test}` | {expectation} | {outcome[0]} | {outcome[1]} |")
        details += [
            "",
            f"### {profile['name']}",
            "",
            "| Applet | Test | Expected | Touch-free | Attended |",
            "|---|---|---|---|---|",
            *rows,
        ]
    return lines, details


def simulated_table(want, found):
    run_ = found.get("simulated")
    lines = [
        "| Card | Applet | " + " | ".join(label for _, label in ALGORITHMS) + " | Checks |",
        "|---|---|" + "---|" * len(ALGORITHMS) + "---|",
    ]
    for name, card in want["simulated"].items():
        covers = " | ".join(mark(card["covers"].get(key, "-")) for key, _ in ALGORITHMS)
        result = run_["cards"].get(name) if run_ else None
        state = "not run yet" if not result else ("passed" if result["outcome"] == "pass" else "**failed**")
        lines.append(f"| {card['card']} | {card['applet']} | {covers} | {state} |")
    sources = []
    if run_:
        sources = ["", f"Run on {run_['date']} from {run_['commit']} ({run_['system']}), built from:", ""]
        for name, card in want["simulated"].items():
            result = run_["cards"].get(name)
            if result:
                sources.append(f"- {card['card']}: {result['sources']}")
    return lines + sources


def render(check):
    want, found = expected(), read_results()
    cards, details = card_tables(want, found)
    simulated = simulated_table(want, found)
    release = version()

    chapter = "\n".join(
        [
            "# Test results",
            "",
            GENERATED,
            "",
            "What the last official runs found: the hardware suites on real cards, and the",
            "simulated cards the checks of `nix flake check` provision. Every outcome is compared",
            "with what the card is expected to do, so a row reads as expected or names what",
            "differs. How the runs are made is in [hardware tests](hardware-tests.md).",
            "",
            "## Real cards",
            "",
            *cards,
            *details,
            "",
            "## Simulated cards",
            "",
            "✓ provisioned and used · refused: turned away before the reset, as the check",
            "asserts · ○ possible, not run yet · — not offered",
            "",
            *simulated,
            "",
        ]
    )
    block = "\n".join(
        [
            f"<!-- results {release} begin -->",
            GENERATED,
            "",
            "Real cards:",
            "",
            *cards,
            "",
            "Simulated cards:",
            "",
            *simulated,
            f"<!-- results {release} end -->",
        ]
    )
    releases = RELEASES.read_text()
    pattern = re.compile(
        rf"<!-- results {re.escape(release)} begin -->.*?<!-- results {re.escape(release)} end -->",
        re.S,
    )
    if not pattern.search(releases):
        fail(f"{RELEASES} has no results block for {release}")
    releases = pattern.sub(lambda _: block, releases)

    stale = [
        path for path, text in ((CHAPTER, chapter), (RELEASES, releases))
        if not path.exists() or path.read_text() != text
    ]
    if check:
        if stale:
            fail(f"{', '.join(map(str, stale))} out of date: run `nix run .#hardware-tests -- --render`")
        print("The rendered results are current")
        return
    CHAPTER.write_text(chapter)
    RELEASES.write_text(releases)
    for path in stale:
        print(f"Rendered {path}")


def main():
    parser = argparse.ArgumentParser(prog="hardware-tests", description=__doc__.split("\n\n")[0])
    what = parser.add_mutually_exclusive_group(required=True)
    what.add_argument("--card", help="a card named in harness/expected.toml and the local .env")
    what.add_argument("--simulated", action="store_true", help="build the simulated cards' checks")
    what.add_argument("--render", action="store_true", help="write the results into the book")
    parser.add_argument("--suite", choices=SUITES, help="touch-free, or attended with a person at the card")
    parser.add_argument("--applet", choices=list(APPLETS), help="one applet only")
    parser.add_argument("--check", action="store_true", help="with --render: fail if the book is out of date")
    args = parser.parse_args()
    if args.card:
        if not args.suite:
            parser.error("--card needs --suite touch-free or --suite attended")
        run_card(args.card, args.suite, args.applet)
    elif args.simulated:
        run_simulated()
    else:
        render(args.check)


if __name__ == "__main__":
    main()
