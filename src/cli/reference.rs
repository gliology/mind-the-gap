//! The book's option reference, rendered from the command line itself.
//!
//! Every verb, its options, their defaults, variables and values come from the one clap
//! command the binary parses with, so the chapter cannot say what the binary does not do. A
//! test holds the committed chapter to this rendering.

use clap::{Arg, ArgAction};

/// How to write the chapter again, said at its top and by the test that compares it
pub const REGENERATE: &str =
    "cargo run --bin mind-the-build -- --reference docs/options-reference.md";

/// The option reference as a chapter of the book
pub fn reference() -> String {
    let command = super::command();
    let mut page = format!(
        "# Option reference\n\n\
         <!-- Generated by\n\
         {REGENERATE}\n\
         from the command line's own definition; change that and generate again, rather than\n\
         this page. A test fails while the two differ. -->\n\n\
         Every option of every verb, as `mind-the-gap <verb> --help` describes it, with its\n\
         default and its variable. [Options](configuration.md) says how options become\n\
         defaults, and [commands](commands.md) what each verb does with them.\n"
    );

    page.push_str(
        "\n## Every verb\n\n\
         The process options and the seeds, which every verb takes. A session or a ceremony\n\
         takes neither on a line: the process options are fixed when the program starts, and\n\
         the seeds are asked for (see [the session](interfaces.md#the-interactive-session)).\n",
    );
    page.push_str(&table(command.get_arguments()));

    for verb in command.get_subcommands() {
        page.push_str(&format!("\n## {}\n\n", verb.get_name()));
        if let Some(about) = verb.get_about() {
            page.push_str(&format!("{}\n", sentence(&about.to_string())));
        }
        if verb.is_hide_set() {
            page.push_str("\nA session's verb alone: on the command line it is refused.\n");
        }
        if verb.get_arguments().next().is_some() {
            page.push_str(&table(verb.get_arguments()));
        } else {
            page.push_str("\nNo options of its own.\n");
        }
        if let Some(after) = verb.get_after_long_help() {
            page.push_str(&format!("\n```text\n{}\n```\n", after.to_string().trim_end()));
        }
    }
    page
}

/// Options as a table in the order a verb's help gives them: the verb's own first, then a
/// row for each help heading and the options under it
fn table<'a>(args: impl Iterator<Item = &'a Arg>) -> String {
    let args: Vec<&Arg> = args.collect();
    let mut headings: Vec<Option<&str>> = vec![None];
    for arg in &args {
        if !headings.contains(&arg.get_help_heading()) {
            headings.push(arg.get_help_heading());
        }
    }
    let mut rows =
        String::from("\n| option | default | variable | what it does |\n|---|---|---|---|\n");
    for heading in headings {
        let under: Vec<&Arg> = args
            .iter()
            .copied()
            .filter(|arg| arg.get_help_heading() == heading)
            .collect();
        if let (Some(heading), false) = (heading, under.is_empty()) {
            rows.push_str(&format!("| **{heading}** | | | |\n"));
        }
        for arg in under {
            rows.push_str(&row(arg));
        }
    }
    rows
}

/// One option's row
fn row(arg: &Arg) -> String {
    let defaults: Vec<String> = arg
        .get_default_values()
        .iter()
        .map(|value| format!("`{}`", value.to_string_lossy()))
        .collect();
    let variable = arg
        .get_env()
        .map(|env| format!("`{}`", env.to_string_lossy()))
        .unwrap_or_default();
    format!("| {} | {} | {variable} | {} |\n", spelling(arg), defaults.join(", "), description(arg))
}

/// An option as a line spells it: `-c, --card <CARD>`, `--legacy`, `--key-seed[=<PHRASE>]`
fn spelling(arg: &Arg) -> String {
    let value = arg
        .get_value_names()
        .and_then(|names| names.first())
        .map_or_else(|| arg.get_id().as_str().to_uppercase(), ToString::to_string);
    if arg.is_positional() {
        return format!("`{value}`");
    }
    let mut spelled = String::new();
    if let Some(short) = arg.get_short() {
        spelled.push_str(&format!("`-{short}`, "));
    }
    let long = format!("--{}", arg.get_long().unwrap_or_default());
    let optional = arg
        .get_num_args()
        .is_some_and(|args| args.min_values() == 0);
    spelled.push_str(&match arg.get_action() {
        ArgAction::SetTrue | ArgAction::SetFalse | ArgAction::Count => format!("`{long}`"),
        _ if optional => format!("`{long}[=<{value}>]`"),
        _ => format!("`{long} <{value}>`"),
    });
    spelled
}

/// What an option does, in one table cell: its whole help, and the values it takes
fn description(arg: &Arg) -> String {
    let help = arg
        .get_long_help()
        .or_else(|| arg.get_help())
        .map(ToString::to_string)
        .unwrap_or_default();
    let mut text = sentence(&help);
    let values: Vec<String> = arg
        .get_possible_values()
        .iter()
        .filter(|value| !value.is_hide_set())
        .map(|value| format!("`{}`", value.get_name()))
        .collect();
    // A flag's values are clap's `true` and `false`, which the flag itself stands for
    if !values.is_empty() && arg.get_action().takes_values() {
        text.push_str(&format!(" One of {}.", values.join(", ")));
    }
    text.replace('|', "\\|")
}

/// Help text as one line of prose, each paragraph ending in a full stop
fn sentence(text: &str) -> String {
    let paragraphs: Vec<String> = text
        .split("\n\n")
        .map(|paragraph| paragraph.split_whitespace().collect::<Vec<_>>().join(" "))
        .filter(|paragraph| !paragraph.is_empty())
        .map(|paragraph| {
            if paragraph.ends_with('.') {
                paragraph
            } else {
                format!("{paragraph}.")
            }
        })
        .collect();
    paragraphs.join(" ")
}
